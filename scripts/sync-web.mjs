// Copies the website's DOM-free modules into src/web/ so the app shares the
// same strings, fee tables, market types and data hooks as sky.shinkaicc.com.
//   node scripts/sync-web.mjs [path/to/apps/web/src]
// Files land verbatim (plus a header); src/web/api.ts and src/web/auth.tsx are
// the app's own adapters and are never overwritten.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const src = process.argv[2] ?? 'D:/SKY/development/apps/web/src'
const out = join(root, 'src/web')
const files = [
  'data.ts', 'vip.ts', 'i18n-extra.ts', 'design/locales.json',
  'market/binance.ts', 'market/catalog.ts', 'market/listings.ts', 'market/hooks.ts',
]
const header = '// AUTO-GENERATED by scripts/sync-web.mjs from the website source. Do not edit here.\n'

for (const f of files) {
  const to = join(out, f)
  mkdirSync(dirname(to), { recursive: true })
  if (f.endsWith('.json')) copyFileSync(join(src, f), to)
  else writeFileSync(to, header + readFileSync(join(src, f), 'utf8'))
  console.log('synced', f)
}
